    const overlay = win({ hwnd: 9, clickThrough: true })
    const editor = win({ hwnd: 2, x: 100, y: 100, w: 500, h: 500 })
    const desk = win({ hwnd: 3 })
    expect(windowAt([overlay, editor, desk], 200, 200)?.hwnd).toBe(2)
    expect(windowAt([overlay, editor, desk], 50, 50)?.hwnd).toBe(3)
