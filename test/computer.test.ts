const ctx = { selfPid: SELF_PID, extra: [] as string[] }

describe('guard', () => {
  test('protects system settings, credential prompts, terminals and password managers', () => {
    expect(protectedReason(win({ exe: 'SystemSettings.exe', title: 'Settings' }), ctx)).toBe('Windows Settings')
    expect(protectedReason(win({ exe: 'CredentialUIBroker.exe', title: 'Windows Security' }), ctx)).toBe('Passkey and sign-in prompts')
    expect(protectedReason(win({ exe: 'WindowsTerminal.exe', title: 'PowerShell' }), ctx)).toBe('Terminals')
    expect(protectedReason(win({ exe: 'cmd.exe', title: 'C:\\WINDOWS\\system32\\cmd.exe' }), ctx)).toBe('Terminals')
    expect(protectedReason(win({ exe: '1Password.exe', title: '1Password' }), ctx)).toBe('Password managers')
    expect(protectedReason(win({ exe: 'mmc.exe', title: 'Services' }), ctx)).toBe('Admin tools')
  })

  test('protects this app by process id, whatever its window says', () => {
    expect(protectedReason(win({ pid: SELF_PID, exe: 'chat-v2.exe', title: 'chat-v2' }), ctx)).toBe('chat-v2 itself')
  })

  test('protects password, passkey and settings pages inside allowed apps', () => {
    expect(protectedReason(win({ exe: 'chrome.exe', title: 'Google Password Manager - Google Chrome' }), ctx)).not.toBeNull()
    expect(protectedReason(win({ exe: 'chrome.exe', title: 'Settings - Manage passkeys - Google Chrome' }), ctx)).not.toBeNull()
    expect(protectedReason(win({ exe: 'helium.exe', title: 'Settings - Helium' }), ctx)).toBe('Settings pages')
    expect(protectedReason(win({ exe: 'firefox.exe', title: 'about:logins — Mozilla Firefox' }), ctx)).not.toBeNull()
    expect(protectedReason(win({ exe: 'explorer.exe', title: 'Run' }), ctx)).toBe('Run dialog')
  })

  test("leaves ordinary apps and their own settings dialogs usable", () => {
    expect(protectedReason(win({ exe: 'Resolve.exe', title: 'DaVinci Resolve - Untitled Project' }), ctx)).toBeNull()
    expect(protectedReason(win({ exe: 'Resolve.exe', title: 'Project Settings: Untitled Project' }), ctx)).toBeNull()
    expect(protectedReason(win({ exe: 'Resolve.exe', title: 'Preferences' }), ctx)).toBeNull()
    expect(protectedReason(win({ exe: 'chrome.exe', title: 'How to color grade - YouTube - Google Chrome' }), ctx)).toBeNull()
    expect(protectedReason(win({ exe: 'explorer.exe', title: 'Downloads' }), ctx)).toBeNull()
  })

  test("windows whose app Windows won't name are protected", () => {
    expect(protectedReason(win({ exe: '', title: 'Something' }), ctx)).not.toBeNull()
  })

  test('user-protected apps match the exe or a word in the title', () => {
    const mine = { selfPid: SELF_PID, extra: ['Steam', 'Banking'] }
    expect(protectedReason(win({ exe: 'steam.exe', title: 'Library' }), mine)).toBe('Steam (protected in Settings)')
    expect(protectedReason(win({ exe: 'chrome.exe', title: 'Online Banking - Chrome' }), mine)).toBe('Banking (protected in Settings)')
    expect(protectedReason(win({ exe: 'notepad.exe', title: 'notes' }), mine)).toBeNull()
  })

  test('refuses to open protected apps by name or id', () => {
    expect(protectedAppName('Settings', 'windows.immersivecontrolpanel_cw5n1h2txyewy!microsoft.windows.immersivecontrolpanel', [])).not.toBeNull()
    expect(protectedAppName('Terminal', 'Microsoft.WindowsTerminal_8wekyb3d8bbwe!App', [])).not.toBeNull()
    expect(protectedAppName('Developer Command Prompt for VS 2022', 'Microsoft.AutoGenerated.{4081}', [])).toBe('Terminals')
    expect(protectedAppName('Bitwarden', 'com.bitwarden.desktop', [])).toBe('Password managers')
    expect(protectedAppName('DaVinci Resolve', 'Blackmagic.Resolve', [])).toBeNull()
    expect(protectedAppName('Runway', 'runway', [])).toBeNull()
  })

  test('blocks shortcuts into protected places', () => {
    expect(protectedChord(parseKeys('Win+R'))).not.toBeNull()
    expect(protectedChord(parseKeys('Win'))).not.toBeNull()
    expect(protectedChord(parseKeys('Ctrl+Alt+Delete'))).not.toBeNull()
    expect(protectedChord(parseKeys('Ctrl+Shift+Esc'))).not.toBeNull()
    expect(protectedChord(parseKeys('Ctrl+Esc'))).not.toBeNull()
    expect(protectedChord(parseKeys('Ctrl+S'))).toBeNull()
    expect(protectedChord(parseKeys('Alt+Tab'))).toBeNull()
  })
})

describe('keys', () => {
  test('parses chords into virtual-key codes, modifiers first', () => {
    expect(parseKeys('Ctrl+Shift+S')).toEqual([0x11, 0x10, 0x53])
    expect(parseKeys('Enter')).toEqual([0x0d])
    expect(parseKeys('alt+F4')).toEqual([0x12, 0x73])
    expect(parseKeys('Ctrl++')).toEqual([0x11, 0xbb])
    expect(parseKeys('Ctrl+/')).toEqual([0x11, 0xbf])
    expect(parseKeys('ArrowDown')).toEqual([0x28])
    expect(() => parseKeys('Ctrl+Hyper')).toThrow('Unknown key')
  })
})

describe('coordinates', () => {
  test('screenshots keep the aspect within 1280×800', () => {
    expect(fitShot(1920, 1080)).toEqual({ w: 1280, h: 720 })
    expect(fitShot(2560, 1600)).toEqual({ w: 1280, h: 800 })
    expect(fitShot(3440, 1440)).toEqual({ w: 1280, h: 536 })
    expect(fitShot(1024, 768)).toEqual({ w: 1024, h: 768 })
  })

  test('maps model pixels to physical pixels and overlay DIPs on a scaled display', () => {
    // A 4K panel at 150%: 3840×2160 physical, 2560×1440 DIPs.
    const f = makeFrame({ x: 0, y: 0, w: 3840, h: 2160, scale: 1.5 })
    expect([f.shotW, f.shotH]).toEqual([1280, 720])
    expect(toPhysical(f, 640, 360)).toEqual({ x: 1920, y: 1080 })
    expect(toOverlay(f, 640, 360)).toEqual({ x: 1280, y: 720 })
    expect(toShot(f, 1920, 1080)).toEqual({ x: 640, y: 360 })
  })

  test('the window that takes a click skips click-through overlays', () => {
    const overlay = win({ hwnd: 9, clickThrough: true })
    const editor = win({ hwnd: 2, x: 100, y: 100, w: 500, h: 500 })
    const desk = win({ hwnd: 3 })
    expect(windowAt([overlay, editor, desk], 200, 200)?.hwnd).toBe(2)
    expect(windowAt([overlay, editor, desk], 50, 50)?.hwnd).toBe(3)
  })

  test('only the visible parts of a protected window are hidden', () => {
    expect(subtract({ x: 0, y: 0, w: 10, h: 10 }, { x: 20, y: 20, w: 5, h: 5 })).toEqual([{ x: 0, y: 0, w: 10, h: 10 }])
    expect(subtract({ x: 0, y: 0, w: 10, h: 10 }, { x: 0, y: 0, w: 10, h: 10 })).toEqual([])
    const settings = win({ hwnd: 5, exe: 'SystemSettings.exe', title: 'Settings', x: 0, y: 0, w: 800, h: 600 })
    const screen = { x: 0, y: 0, w: 1920, h: 1080 }
    const reason = (w: typeof settings) => protectedReason(w, ctx)
    // Behind a full-screen editor it shows nowhere, so nothing is painted over.
    expect(hiddenRegions([win({ hwnd: 1, w: 1920, h: 1080 }), settings], reason, screen)).toEqual([])
    // Half covered: only the uncovered half is hidden.
    const parts = hiddenRegions([win({ hwnd: 1, x: 400, y: 0, w: 1520, h: 1080 }), settings], reason, screen)
    expect(parts[0]!.parts).toEqual([{ x: 0, y: 0, w: 400, h: 600 }])
  })
})

describe('marks', () => {
  test('keeps well-formed marks and drops the rest', () => {
    const marks = readMarks([
      { kind: 'circle', x: 10, y: 10, w: 40, h: 20, label: 'Export', color: 'blue' },
      { kind: 'arrow', from: [0, 0], to: [50, 50] },
      { kind: 'path', points: [[0, 0], [5, 5], [9, 2]] },
      { kind: 'text', x: 5, y: 5, text: 'Click here' },
      { kind: 'box', x: 1, y: 1, w: -5, h: 5 },
      { kind: 'arrow', from: [0], to: [1, 1] },
      { kind: 'laser', x: 0, y: 0 },
      { kind: 'circle', x: 1, y: 1, w: 5, h: 5, color: 'chartreuse' }
    ])
    expect(marks.map((m) => m.kind)).toEqual(['circle', 'arrow', 'path', 'text', 'circle'])
    expect(marks[0]).toMatchObject({ label: 'Export', color: 'blue' })
    expect('color' in marks[4]!).toBe(false)
  })
})

const service = (desktop = fakeDesktop(), config: Record<string, unknown> = {}) => {
  const dir = mkdtempSync(join(tmpdir(), 'chat-v2-cu-'))
  writeFileSync(join(dir, 'config.json'), JSON.stringify(config))
  const paths = AppPaths.layer(dir)
  const settings = SettingsStore.layer({ encrypt: (s) => s, decrypt: (s) => s }).pipe(Layer.provide(paths))
  const runtime = ManagedRuntime.make(Computer.layer(desktop.ports).pipe(Layer.provide(Layer.mergeAll(settings, paths))))
  const run = <A, E>(eff: Effect.Effect<A, E, Computer>) => runtime.runPromise(eff)
  const tool = (name: string, args: object = {}) => run(Computer.use((c) => runComputerTool(c, name, JSON.stringify(args))))
  return { desktop, run, tool, runtime }
}

describe('computer service', () => {
  test('a click lands at the physical point under the model pixel, after the cursor glides there', async () => {
    const t = service()
    await t.run(Computer.use((c) => c.begin('reply-1')))
    expect(t.desktop.chat).toEqual(['hide'])
    const look = await t.tool('computer_screenshot')
    expect(look.text).toContain('1280×720')
    expect(look.text).toContain('"notes.txt - Notepad" (notepad.exe)')
    expect(look.image).toBe('data:image/jpeg;base64,SHOT')

    const out = await t.tool('computer_click', { x: 100, y: 200, target: 'File menu' })
    expect(out.step).toEqual({ tool: 'computer_click', label: 'Clicked “File menu” in Notepad', ok: true })
    // Posted to the window under the point; the user's mouse never moves.
    expect(t.desktop.input).toEqual(['click 1 150,300 left'])
    expect(t.desktop.state.cursor).toEqual({ x: 50, y: 50 })
    expect(t.desktop.overlay).toContainEqual({ type: 'cursor', x: 150, y: 300, label: 'Clicking File menu', action: 'click' })
    expect(out.image).toBeDefined()

    await t.run(Computer.use((c) => c.end('reply-1')))
    expect(t.desktop.overlay.at(-1)).toEqual({ type: 'status', state: 'off', label: '' })
    expect(t.desktop.chat).toEqual(['hide', 'show'])
  })

  test('refuses to click or type into a protected window, and ends the run', async () => {
    const settings = win({ hwnd: 7, pid: 300, exe: 'SystemSettings.exe', title: 'Settings', x: 0, y: 0, w: 900, h: 700 })
    const t = service(fakeDesktop([settings, win({ hwnd: 1 })]))
    await t.run(Computer.use((c) => c.begin('r')))
    const look = await t.tool('computer_screenshot')
    expect(look.text).toContain('Hidden from you')
    expect(look.text).not.toContain('"Settings"')
    // The settings window is painted over in the screenshot (900×700 physical → 600×467 shot px, plus margin).
    expect(t.desktop.covers.at(-1)).toEqual([{ x: -2, y: -2, w: 604, h: 471 }])

    const click = await t.tool('computer_click', { x: 100, y: 100, target: 'Bluetooth' })
    expect(click.halt).toContain('Windows Settings is protected')
    expect(click.step.ok).toBe(false)
    const typed = await t.tool('computer_type', { text: 'hello' })
    expect(typed.halt).toBeDefined()
    expect(t.desktop.input).toEqual([])
    // Outside the protected window, clicks are fine.
    const ok = await t.tool('computer_click', { x: 1000, y: 600, target: 'Notepad' })
    expect(ok.halt).toBeUndefined()
  })

  test("never touches this app's own window", async () => {
    const t = service(fakeDesktop([win({ hwnd: 3, pid: SELF_PID, exe: 'chat-v2.exe', title: 'chat-v2' })]))
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    expect((await t.tool('computer_click', { x: 10, y: 10, target: 'Stop' })).halt).toBeDefined()
    expect((await t.tool('computer_key', { keys: 'Ctrl+A' })).halt).toBeDefined()
    expect(t.desktop.input).toEqual([])
  })

  test('refuses Windows-key shortcuts and protected apps by name', async () => {
    const t = service()
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    expect((await t.tool('computer_key', { keys: 'Win+R' })).halt).toBeDefined()
    expect((await t.tool('computer_open_app', { name: 'Settings' })).halt).toBeDefined()
    expect((await t.tool('computer_open_app', { name: 'command prompt' })).halt).toBeDefined()
    expect(t.desktop.input).toEqual([])
    const resolve = await t.tool('computer_open_app', { name: 'davinci' })
    expect(resolve.step.label).toBe('Opened DaVinci Resolve')
    expect(t.desktop.input).toEqual(['launch resolve'])
  })

  test('the user can keep using their mouse while it works', async () => {
    const desktop = fakeDesktop()
    const t = service(desktop)
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    await t.tool('computer_move', { x: 10, y: 10, target: 'Menu' })
    desktop.state.cursor = { x: 900, y: 700 }
    const next = await t.tool('computer_click', { x: 20, y: 20, target: 'Save' })
    expect(next.halt).toBeUndefined()
    await t.tool('computer_drag', { from: [100, 100], to: [200, 150], target: 'Clip' })
    await t.tool('computer_scroll', { x: 400, y: 300, direction: 'down', amount: 3 })
    expect(desktop.input).toEqual(['hover 1 15,15', 'click 1 30,30 left', 'drag 1 150,150 to 300,225', 'wheel 1 600,450 0,-3'])
    expect(desktop.state.cursor).toEqual({ x: 900, y: 700 })
  })

  test('keys go to the app it last clicked in, brought back to the front if the user moved on', async () => {
    const notepad = win({ hwnd: 1, pid: 100, x: 0, y: 0, w: 900, h: 1040 })
    const browser = win({ hwnd: 2, pid: 200, exe: 'chrome.exe', title: 'News - Chrome', x: 960, y: 0, w: 960, h: 1040 })
    const desktop = fakeDesktop([notepad, browser])
    const t = service(desktop)
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    await t.tool('computer_click', { x: 100, y: 100, target: 'Text area' })
    // The user clicks into the browser meanwhile.
    desktop.state.foreground = 2
    await t.tool('computer_type', { text: 'hi' })
    expect(desktop.input).toEqual(['click 1 150,150 left', 'focus 1', 'text hi'])
  })

  test("won't start when the input helper's coordinates are scaled", async () => {
    const desktop = fakeDesktop()
    desktop.state.cursor = { x: 400, y: 300 }
    desktop.skewCursor = true
    const t = service(desktop)
    await expect(t.run(Computer.use((c) => c.begin('r')))).rejects.toThrow('scaling')
    expect(desktop.chat).toEqual([])
  })

  test('only one reply has the computer at a time', async () => {
    const t = service()
    await t.run(Computer.use((c) => c.begin('a')))
    await expect(t.run(Computer.use((c) => c.begin('b')))).rejects.toThrow('Another chat')
    await t.run(Computer.use((c) => c.end('a')))
    await t.run(Computer.use((c) => c.begin('b')))
  })

  test('marks are drawn in overlay DIPs, outlive the reply, and clear when it acts again', async () => {
    const t = service()
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    const out = await t.tool('computer_annotate', { marks: [{ kind: 'circle', x: 100, y: 100, w: 40, h: 20, label: 'Color page' }] })
    expect(out.step.label).toBe('Marked “Color page”')
    const drawn = t.desktop.overlay.find((e) => e.type === 'marks')
    expect(drawn).toMatchObject({ marks: [{ kind: 'circle', x: 150, y: 150, w: 60, h: 30, color: 'red', label: 'Color page' }] })
    await t.run(Computer.use((c) => c.end('r')))
    // With marks up, the chat stays out of the way and the overlay offers to bring it back.
    expect(t.desktop.overlay.at(-1)).toEqual({ type: 'status', state: 'done', label: 'Done' })
    expect(t.desktop.chat).toEqual(['hide'])

    const before = t.desktop.overlay.length
    await t.run(Computer.use((c) => c.begin('r2')))
    expect(t.desktop.overlay.slice(before)).toContainEqual({ type: 'clear' })
  })

  test('in computer mode the cursor stays up between tasks, and hints say what the reply is doing', async () => {
    const t = service()
    const last = () => t.desktop.overlay.at(-1)
    await t.run(Computer.use((c) => c.setMode(true)))
    expect(t.desktop.overlay.slice(-2)).toEqual([{ type: 'mode', follow: true }, { type: 'status', state: 'idle', label: '' }])
    // Before it takes the mouse (while it reads up on the app), the hint goes under the cursor.
    await t.run(Computer.use((c) => c.hint('Reading brawlhalla.wiki.gg')))
    expect(last()).toEqual({ type: 'hint', label: 'Reading brawlhalla.wiki.gg' })
    await t.run(Computer.use((c) => c.begin('r')))
    await t.run(Computer.use((c) => c.hint('Thinking…')))
    expect(last()).toEqual({ type: 'status', state: 'working', label: 'Thinking…' })
    // Done without marks: back to following the user, and the chat comes back.
    await t.run(Computer.use((c) => c.end('r')))
    expect(last()).toEqual({ type: 'status', state: 'idle', label: '' })
    expect(t.desktop.chat).toEqual(['hide', 'show'])
    await t.run(Computer.use((c) => c.setMode(false)))
    expect(last()).toEqual({ type: 'status', state: 'off', label: '' })
    // Out of computer mode, hints show nowhere.
    const sent = t.desktop.overlay.length
    await t.run(Computer.use((c) => c.hint('Thinking…')))
    expect(t.desktop.overlay.length).toBe(sent)
  })

  test('leaving computer mode keeps marks the user has not cleared', async () => {
    const t = service()
    await t.run(Computer.use((c) => c.setMode(true)))
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    await t.tool('computer_annotate', { marks: [{ kind: 'box', x: 10, y: 10, w: 40, h: 20, label: 'Camera mode' }] })
    await t.run(Computer.use((c) => c.end('r')))
    expect(t.desktop.overlay.at(-1)).toEqual({ type: 'status', state: 'done', label: 'Done' })
    await t.run(Computer.use((c) => c.setMode(false)))
    expect(t.desktop.overlay.at(-1)).toEqual({ type: 'mode', follow: false })
  })

  test('the overlay Stop button stops the reply that has control', async () => {
    const t = service()
    const stopped: string[] = []
    await t.run(Computer.use((c) => Effect.sync(() => c.onStop((id) => stopped.push(id)))))
    await t.run(Computer.use((c) => c.begin('reply-9')))
    t.desktop.stop!()
    expect(stopped).toEqual(['reply-9'])
  })

  test('saved tips come back when their app is in front', async () => {
    const t = service(fakeDesktop([win({ hwnd: 4, exe: 'Resolve.exe', title: 'DaVinci Resolve - Project 1' })]))
    await t.run(Computer.use((c) => c.begin('r')))
    const saved = await t.tool('computer_save_tip', { app: 'DaVinci Resolve', tip: 'The Deliver page is the rocket icon at the bottom right.' })
    expect(saved.step.label).toBe('Saved a tip for DaVinci Resolve')
    const look = await t.tool('computer_screenshot')
    expect(look.text).toContain('Tips you saved earlier for DaVinci Resolve:\n- The Deliver page is the rocket icon')
    const tips = await t.run(Computer.use((c) => c.tips))
    expect(await t.run(Computer.use((c) => c.removeTip(tips[0]!.id)))).toEqual([])
  })

  test('acting before looking asks for a screenshot first', async () => {
    const t = service()
    await t.run(Computer.use((c) => c.begin('r')))
    const out = await t.tool('computer_click', { x: 1, y: 1, target: 'x' })
    expect(out.text).toContain('Take a screenshot first')
    expect(out.halt).toBeUndefined()
  })

  test('points off the screenshot are refused', async () => {
    const t = service()
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    const out = await t.tool('computer_click', { x: 1400, y: 10, target: 'x' })
    expect(out.text).toContain('outside the screenshot, which is 1280×720')
    expect(t.desktop.input).toEqual([])
  })
})

describe('zoom', () => {
  test('captures the region at full resolution, magnified, without changing the frame', async () => {
    const desktop = fakeDesktop()
    const crops: unknown[] = []
    const capture = desktop.ports.screen.capture
    desktop.ports.screen.capture = async (size, cover, crop) => (crops.push({ size, crop }), capture(size, cover, crop))
    const t = service(desktop)
    await t.run(Computer.use((c) => c.begin('r')))
    await t.tool('computer_screenshot')
    const out = await t.tool('computer_zoom', { x: 100, y: 50, w: 200, h: 100 })
    expect(out.step.label).toBe('Looked closer')
    expect(out.image).toBeDefined()
    // 200×100 screenshot px is 300×150 physical; 3× at most, so 900×450.
    expect(crops.at(-1)).toEqual({ size: { w: 900, h: 450 }, crop: { x: 150, y: 75, w: 300, h: 150 } })
    expect(out.text).toContain('magnified 4.5×')
    // Clicks still use the full screenshot's coordinates.
    await t.tool('computer_click', { x: 100, y: 100, target: 'x' })
    expect(desktop.input).toEqual(['click 1 150,150 left'])
  })
})
